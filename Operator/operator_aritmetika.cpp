#include <iostream>
using namespace std;

int main() {

    // Deklarasi dan inisialisasi variabel
    int a = 20, b = 7;

    // Pejumlahan
    cout << "Hasil " << a << " + " << b << " = " << a + b << endl;

    // Pengurangan
    cout << "Hasil " << a << " - " << b << " = " << a - b << endl;

    // Perkalian
    cout << "Hasil " << a << " * " << b << " = " << a * b << endl;

    // Pembagian
    cout << "Hasil " << a << " / " << b << " = " << a / b << endl;

    // Modulus atau sisa bagi
    cout << "Hasil " << a << " % " << b << " = " << a % b << endl;

    // Increment
    cout << "Hasil increment " << a << " = " << ++a << endl;

    // Decrement
    cout << "Hasil decrement " << a << " = " << --a << endl;

    return 0;
}