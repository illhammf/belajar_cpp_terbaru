#include <iostream>
using namespace std;

int main() {

    // Deklarasi dan inisialisasi varibel
    int angka = 10;

    // Pernyataan kondisi apakah angka 10 lebih besar dari 20
    if (angka > 20) {
        cout << angka << " lebih besar dari 20" << endl;
    }
    // Jika tidak
    else {
        cout << angka << " lebih kecil dari 20" << endl;
    }
    
    return 0;
}